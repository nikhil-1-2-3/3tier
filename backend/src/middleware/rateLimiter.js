import rateLimit from 'express-rate-limit';

// Rate limit for authentication attempts (15 minutes, 20 requests)
export const authLimiter = rateLimit({
  windowMs: 15 * 60 * 1000,
  max: 20,
  standardHeaders: true,
  legacyHeaders: false,
  message: {
    success: false,
    message: 'Too many authentication attempts. Please try again after 15 minutes.',
  },
});

// Rate limit for public bookings and support enquiries (15 minutes, 30 requests)
export const submissionLimiter = rateLimit({
  windowMs: 15 * 60 * 1000,
  max: 30,
  standardHeaders: true,
  legacyHeaders: false,
  message: {
    success: false,
    message: 'Too many requests submitted. Please wait a few moments before trying again.',
  },
});
